local tables = { es = es, en = en }

-- "es_CL", "es", "en_US"... -> "es" or "en"
function I18n.language_from(code)
    local lang = tostring(code or ""):match("^(%a%a)")
    return tables[lang and lang:lower()] and lang:lower() or "en"
end

function I18n.strings(code)
    return tables[I18n.language_from(code)]
end

I18n.tables = tables
return I18n
